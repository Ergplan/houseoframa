// Generates docs/BLUEPRINT.md from the types in packages/shared/src (CLAUDE.md §4, living documents).
// Usage: node scripts/gen-blueprint-doc.mjs          writes the document
//        node scripts/gen-blueprint-doc.mjs --check  exits 1 when the document on disk differs
// Every exported type and every field must carry a doc comment; the generator refuses otherwise.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOC_PATH = path.join(root, 'docs/BLUEPRINT.md');
// Fixed order: the Blueprint first, then what is built on top of it.
const SOURCES = ['blueprint.ts', 'trail.ts', 'ceremony.ts', 'audit.ts'].map((f) =>
  path.join(root, 'packages/shared/src', f),
);

function docOf(node, sf) {
  const ranges = ts.getLeadingCommentRanges(sf.text, node.getFullStart()) ?? [];
  const docs = ranges
    .map((r) => sf.text.slice(r.pos, r.end))
    .filter((c) => c.startsWith('/**'))
    .map((c) =>
      c
        .replace(/^\/\*\*|\*\/$/g, '')
        .split('\n')
        .map((l) => l.replace(/^\s*\*\s?/, '').trim())
        .filter(Boolean)
        .join(' '),
    );
  return docs.at(-1) ?? null;
}

const cell = (s) => s.replace(/\s+/g, ' ').replace(/\|/g, '\\|');

/** Returns [{name, kind, doc, typeText?, fields?: [{name, type, optional, doc}]}] or throws on missing docs. */
export function collectTypes(sources = SOURCES) {
  const out = [];
  const missing = [];
  for (const file of sources) {
    const sf = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
    const rel = path.relative(root, file);
    for (const stmt of sf.statements) {
      const exported = stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
      if (!exported) continue;
      if (ts.isTypeAliasDeclaration(stmt)) {
        const doc = docOf(stmt, sf);
        if (!doc) missing.push(`${rel}: type ${stmt.name.text}`);
        out.push({
          name: stmt.name.text,
          kind: 'type',
          file: rel,
          doc,
          typeText: stmt.type.getText(sf),
        });
      } else if (ts.isInterfaceDeclaration(stmt)) {
        const doc = docOf(stmt, sf);
        if (!doc) missing.push(`${rel}: interface ${stmt.name.text}`);
        const fields = stmt.members.filter(ts.isPropertySignature).map((m) => {
          const fdoc = docOf(m, sf);
          if (!fdoc) missing.push(`${rel}: ${stmt.name.text}.${m.name.getText(sf)}`);
          return {
            name: m.name.getText(sf),
            type: m.type?.getText(sf) ?? 'unknown',
            optional: Boolean(m.questionToken),
            doc: fdoc,
          };
        });
        out.push({ name: stmt.name.text, kind: 'interface', file: rel, doc, fields });
      }
    }
  }
  if (missing.length)
    throw new Error(`Undocumented shared types or fields:\n  ${missing.join('\n  ')}`);
  return out;
}

export function render(types = collectTypes()) {
  const lines = [
    '# Blueprint schema',
    '',
    '<!-- Generated by scripts/gen-blueprint-doc.mjs from packages/shared/src. Do not edit by hand; CI fails on drift. -->',
    '',
    'The types every House of Rama package shares. The Blueprint is written only by `packages/blueprint` from a git checkout (Invariant 1).',
    '',
  ];
  for (const t of types) {
    lines.push(`## ${t.name}`, '', t.doc, '', `Source: \`${t.file}\``, '');
    if (t.kind === 'type') {
      lines.push('```ts', `type ${t.name} = ${t.typeText};`, '```', '');
    } else {
      lines.push('| Field | Type | Required | Meaning |', '| --- | --- | --- | --- |');
      for (const f of t.fields) {
        lines.push(
          `| \`${f.name}\` | \`${cell(f.type)}\` | ${f.optional ? 'no' : 'yes'} | ${cell(f.doc)} |`,
        );
      }
      lines.push('');
    }
  }
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const doc = render();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(DOC_PATH, 'utf8');
    } catch {
      // missing counts as drift
    }
    if (current !== doc) {
      console.error('docs/BLUEPRINT.md is out of date: run `pnpm gen:blueprint-doc`.');
      process.exit(1);
    }
    console.log('docs/BLUEPRINT.md is up to date.');
  } else {
    writeFileSync(DOC_PATH, doc);
    console.log('wrote docs/BLUEPRINT.md');
  }
}
