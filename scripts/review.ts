// The independent stage reviewer (CLAUDE.md §1, "Independent review"). It goes through packages/model
// as the auditor role, so it is a different vendor from the builder (Invariant 5), and it receives
// only the stage diff, CLAUDE.md and the stage prompt.
//   pnpm review <stage>   → appends the run to docs/reports/stage-<N>.review.md and prints it
import { execFileSync } from 'node:child_process';
import { appendFileSync, existsSync, readFileSync } from 'node:fs';
import { z } from 'zod';
import { call } from '@rama/model';

if (existsSync('.env')) process.loadEnvFile('.env');

// Generated files whose bodies are left out of the diff (the reviewer is told how each is generated and checked).
const ELIDED = {
  'blueprint/self.json':
    'generated by `pnpm extract:self`; `pnpm check:self` in the watcher and CI fails on drift',
  'pnpm-lock.yaml': 'generated by `pnpm install`; CI installs with --frozen-lockfile',
};

const Review = z.object({
  items: z.array(
    z.object({
      item: z.enum(['a', 'b', 'c', 'd', 'e']),
      verdict: z.enum(['upheld', 'violation', 'cannot-tell', 'not-applicable']),
      notes: z.string(),
    }),
  ),
  findings: z.array(
    z.object({
      item: z.enum(['a', 'b', 'c', 'd', 'e']),
      kind: z.enum(['code-defect', 'report-claim', 'not-a-defect']),
      file: z.string(),
      line: z.number().nullable(),
      text: z.string(),
    }),
  ),
});

const stage = Number(process.argv[2]);
if (!Number.isInteger(stage) || stage < 1) throw new Error('usage: pnpm review <stage>');

const git = (...args: string[]) =>
  execFileSync('git', args, { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
const base = `stage-${stage}-start`;
const exclusions = Object.keys(ELIDED).map((p) => `:(exclude)${p}`);
const elided = Object.entries(ELIDED)
  .filter(([p]) => git('diff', '--stat', `${base}..HEAD`, '--', p).trim())
  .map(([p, how]) => `# ${p}: changed; body left out of this diff (${how})`);
const diff = [...elided, git('diff', `${base}..HEAD`, '--', '.', ...exclusions)].join('\n');

const master = readFileSync('docs/MASTER-PROMPT.md', 'utf8');
const heading = `### Stage ${stage} — `;
const start = master.indexOf(heading);
if (start === -1) throw new Error(`Stage ${stage} not found in docs/MASTER-PROMPT.md`);
const end = master.indexOf('\n### Stage ', start + heading.length);
const stagePrompt = master.slice(start, end === -1 ? master.indexOf('\n## ', start + 1) : end);

const head = git('rev-parse', '--short', 'HEAD').trim();
const res = await call({
  name: 'reviewer',
  version: 1,
  input: { stage, claudeMd: readFileSync('CLAUDE.md', 'utf8'), stagePrompt, diff },
  output: Review,
  role: 'auditor',
  siteId: 'self',
  createdBy: 'rama:reviewer@1',
  maxTokens: 32_000,
});

const lines = [
  `## Run at ${head} — ${new Date().toISOString()}`,
  '',
  `Vendor ${res.vendor}, model ${res.model}, call ${res.callId}, ${res.attempts} attempt(s), ${res.inputTokens} input / ${res.outputTokens} output tokens. Diff: ${diff.length} characters.`,
  '',
  '| Item | Verdict | Notes |',
  '| --- | --- | --- |',
  ...res.output.items.map(
    (i) => `| ${i.item} | ${i.verdict} | ${i.notes.replace(/\|/g, '\\|').replace(/\n/g, ' ')} |`,
  ),
  '',
  ...(res.output.findings.length
    ? res.output.findings.map(
        (f, n) =>
          `${n + 1}. **${f.kind}** (${f.item}) \`${f.file}${f.line ? `:${f.line}` : ''}\` — ${f.text.replace(/\n/g, ' ')}`,
      )
    : ['No findings.']),
  '',
];
const out = `docs/reports/stage-${stage}.review.md`;
if (!existsSync(out))
  appendFileSync(
    out,
    `# Stage ${stage} — independent review runs\n\nWritten by \`scripts/review.ts\`; one section per run, newest last.\n\n`,
  );
appendFileSync(out, lines.join('\n') + '\n');
console.log(lines.join('\n'));
